export interface GalleryImage {
  src: string;
  alt: string;
}

const toGallery = (name: string, images: { src: string }[]): GalleryImage[] =>
  images.map((image, index) => ({
    src: image.src,
    alt: `${name} view ${index + 1}`,
  }));

